/**
 * Reads every image in public/art, works out its real pixel dimensions, and
 * writes src/art.ts.
 *
 * Dimensions are read straight out of the file header — no dependency, no
 * decoding. The film needs each painting's aspect ratio to lay it out before
 * the browser has loaded anything, so this has to be known at build time.
 *
 * Run it whenever you add or replace a painting:
 *     npm run manifest
 */
import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, extname, basename, dirname } from 'node:path';

const ART_DIR = 'public/art';
const OUT = 'src/art.ts';

function pngSize(buf) {
  // IHDR is always the first chunk: width at byte 16, height at byte 20.
  if (buf.readUInt32BE(0) !== 0x89504e47) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function jpegSize(buf) {
  if (buf[0] !== 0xff || buf[1] !== 0xd8) return null;
  let i = 2;
  while (i < buf.length - 9) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    // Standalone markers carry no length payload.
    if (marker === 0xd8 || marker === 0xd9 || (marker >= 0xd0 && marker <= 0xd7)) {
      i += 2;
      continue;
    }
    const len = buf.readUInt16BE(i + 2);
    // SOF0..SOF15, excluding DHT (c4), JPG (c8) and DAC (cc).
    const isSOF =
      marker >= 0xc0 && marker <= 0xcf &&
      marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;
    if (isSOF) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  return null;
}

function sizeOf(path) {
  const buf = readFileSync(path);
  const ext = extname(path).toLowerCase();
  if (ext === '.png') return pngSize(buf);
  if (ext === '.jpg' || ext === '.jpeg') return jpegSize(buf);
  return null;
}

if (!existsSync(ART_DIR)) {
  mkdirSync(ART_DIR, { recursive: true });
  console.error(`Created ${ART_DIR}. Put your painting files in it and run again.`);
  process.exit(1);
}

const files = readdirSync(ART_DIR)
  .filter((f) => /\.(jpe?g|png)$/i.test(f))
  .sort();

if (files.length === 0) {
  console.error(`No images found in ${ART_DIR}. Add .jpg or .png files and run again.`);
  process.exit(1);
}

const entries = [];
for (const f of files) {
  const size = sizeOf(join(ART_DIR, f));
  if (!size) {
    console.warn(`  skipped ${f} — could not read its dimensions`);
    continue;
  }
  const id = basename(f, extname(f));
  entries.push({ id, file: `art/${f}`, ...size, aspect: size.width / size.height });
  console.log(`  ${f.padEnd(30)} ${size.width}x${size.height}`);
}

const body = `/**
 * GENERATED by scripts/build-manifest.mjs — do not edit by hand.
 * Run \`npm run manifest\` after adding or replacing paintings in public/art.
 */

export type Art = {
  id: string;
  file: string;
  width: number;
  height: number;
  /** width / height — 1 is square, >1 landscape, <1 portrait */
  aspect: number;
};

export const ART: Art[] = ${JSON.stringify(entries, null, 2)};

const byId = new Map(ART.map((a) => [a.id, a]));

/** Look a painting up by id, falling back to the first one so a renamed
 *  file never crashes a render mid-shot. */
export const art = (id: string): Art => byId.get(id) ?? ART[0];

/** Every painting whose shape matches, for laying out a wall. */
export const portrait = ART.filter((a) => a.aspect < 0.92);
export const square = ART.filter((a) => a.aspect >= 0.92 && a.aspect <= 1.08);
export const landscape = ART.filter((a) => a.aspect > 1.08);
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`\nWrote ${OUT} — ${entries.length} paintings.`);
